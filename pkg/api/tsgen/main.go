// Command tsgen writes the HTTP API's JSON types and paths as TypeScript for
// the web interface, so the browser reads the same contract the Go code
// does: tsgen <routes.go> <out.ts>.
package main

import (
	"cmp"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"reflect"
	"strconv"
	"strings"
	"time"

	"github.com/mainplane-ai/mainplane/pkg/api"
)

// roots are the shapes the web interface sends or reads; each type they
// hold comes along.
var roots = []any{api.Info{}, api.AgentInfo{}, api.AgentCreate{}, api.Create{}, api.ProviderInfo{}}

type gen struct {
	decls []string
	seen  map[string]reflect.Type
}

func main() {
	if len(os.Args) != 3 {
		fail(fmt.Errorf("usage: tsgen <routes.go> <out.ts>"))
	}
	g := gen{seen: map[string]reflect.Type{}}
	for _, r := range roots {
		g.ts(reflect.TypeOf(r))
	}
	var b strings.Builder
	b.WriteString("// Generated by pkg/api/tsgen from pkg/api: go generate ./pkg/web. Do not edit.\n\n")
	for _, d := range g.decls {
		b.WriteString(d + "\n")
	}
	b.WriteString("\n// The paths of the HTTP API; fill one with path.\nexport const paths = {\n")
	for _, p := range paths(os.Args[1]) {
		fmt.Fprintf(&b, "  %s: %q,\n", p[0], p[1])
	}
	b.WriteString("} as const\n\n")
	b.WriteString("// path is p with each {wildcard} filled by the next of args, escaped.\n")
	b.WriteString("export function path(p: string, ...args: string[]): string {\n")
	b.WriteString("  const out = p.replace(/\\{[^}]+\\}/g, () => {\n")
	b.WriteString("    if (!args.length) throw new Error(`path ${p}: too few args`)\n")
	b.WriteString("    return encodeURIComponent(args.shift()!)\n")
	b.WriteString("  })\n")
	b.WriteString("  if (args.length) throw new Error(`path ${p}: too many args`)\n")
	b.WriteString("  return out\n}\n")
	if err := os.WriteFile(os.Args[2], []byte(b.String()), 0o644); err != nil {
		fail(err)
	}
}

// paths is each name and value of the Path constants in file, in order,
// without the Path suffix.
func paths(file string) [][2]string {
	f, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
	if err != nil {
		fail(err)
	}
	var out [][2]string
	ast.Inspect(f, func(n ast.Node) bool {
		if v, ok := n.(*ast.ValueSpec); ok && len(v.Names) == 1 && len(v.Values) == 1 && strings.HasSuffix(v.Names[0].Name, "Path") {
			s, err := strconv.Unquote(v.Values[0].(*ast.BasicLit).Value)
			if err != nil {
				fail(err)
			}
			out = append(out, [2]string{strings.TrimSuffix(v.Names[0].Name, "Path"), s})
		}
		return true
	})
	return out
}

// ts is t as a TypeScript type: a named struct is declared once, by its Go
// name, and two structs of one name are a failure.
func (g *gen) ts(t reflect.Type) string {
	switch {
	case t == reflect.TypeFor[time.Time]():
		return "string"
	case t == reflect.TypeFor[json.RawMessage]():
		return "unknown"
	}
	switch k := t.Kind(); {
	case k == reflect.String:
		return "string"
	case k == reflect.Bool:
		return "boolean"
	case k >= reflect.Int && k <= reflect.Uint64 && k != reflect.Uintptr, k == reflect.Float32, k == reflect.Float64:
		return "number"
	case k == reflect.Slice && t.Elem().Kind() == reflect.Uint8:
		return "string" // base64
	case k == reflect.Slice, k == reflect.Array:
		return g.ts(t.Elem()) + "[]"
	case k == reflect.Map:
		return "Record<string, " + g.ts(t.Elem()) + ">"
	case k == reflect.Pointer:
		return g.ts(t.Elem())
	case k == reflect.Interface:
		return "unknown"
	case k == reflect.Struct && t.Name() == "":
		return g.fields(t)
	case k == reflect.Struct:
		if had, ok := g.seen[t.Name()]; ok {
			if had != t {
				fail(fmt.Errorf("two types named %s: %v and %v", t.Name(), had, t))
			}
			return t.Name()
		}
		g.seen[t.Name()] = t
		g.decls = append(g.decls, fmt.Sprintf("export type %s = %s", t.Name(), g.fields(t)))
		return t.Name()
	}
	fail(fmt.Errorf("no TypeScript for %v", t))
	return ""
}

// fields is a struct's JSON object type: embedded structs' fields inline,
// a field that may be left out optional.
func (g *gen) fields(t reflect.Type) string {
	var fs []string
	var walk func(t reflect.Type)
	walk = func(t reflect.Type) {
		for f := range t.Fields() {
			tag := f.Tag.Get("json")
			name, opts, _ := strings.Cut(tag, ",")
			if !f.IsExported() || name == "-" {
				continue
			}
			if f.Anonymous && name == "" {
				walk(f.Type)
				continue
			}
			opt, null, k := "", "", f.Type.Kind()
			if strings.Contains(opts, "omitempty") || strings.Contains(opts, "omitzero") || k == reflect.Pointer {
				opt = "?"
			} else if k == reflect.Slice && f.Type.Elem().Kind() != reflect.Uint8 || k == reflect.Map {
				null = " | null" // a nil slice or map is sent as null
			}
			fs = append(fs, fmt.Sprintf("%s%s: %s%s", cmp.Or(name, f.Name), opt, g.ts(f.Type), null))
		}
	}
	walk(t)
	return "{ " + strings.Join(fs, "; ") + " }"
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "tsgen:", err)
	os.Exit(1)
}
